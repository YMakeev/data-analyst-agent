#!/usr/bin/env sh
# Старт сервера в хмарі.
#
# Керована база в хмарі не виконує db/init/*.sql сама — на відміну від
# локального контейнера. Тому при першому запуску ми розгортаємо схему й
# створюємо read-only роль явно.
#
# За замовчуванням усе це ВИМКНЕНО: перезаписати дані в задеплоєній базі
# випадковим рестартом — саме той сюрприз, якого не хочеться. Вмикається
# змінною SEED_ON_START=1, і зазвичай лише один раз, після чого її прибирають.

set -e

if [ "$SEED_ON_START" = "1" ]; then
    echo "==> SEED_ON_START=1: розгортаю схему й роль"
    python db/bootstrap.py
    echo "==> Заливаю демо-дані"
    python db/seed.py
fi

if [ ! -f ml/model.pkl ]; then
    echo "==> Моделі немає, тренуюсь"
    python ml/train.py || echo "!! Натренувати не вдалось; predict_churn буде недоступний"
fi

echo "==> Стартую MCP-сервер на порту ${PORT:-8000}"
exec python -m server.main
